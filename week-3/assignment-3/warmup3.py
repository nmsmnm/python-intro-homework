# Warmup 3 - Boolean Expression Practice

print(not True and False)  # not True is False, so the result is False

print(True or False and False)  # and goes first, True or False is True

print(not (5 > 3))  # 5 > 3 is True, not True is False

print(10 == 10 and 4 != 4)  # first is True, second is False, result is False

print(not False or not True)  # True or False is True